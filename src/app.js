function trendTypeKey(trend) {
  if (trend.velocity >= 36 && trend.score >= 84) return "typeExploding";
  if (trend.velocity >= 24) return "typeEmerging";
  if (trend.competition === "low" && trend.score >= 76) return "typeUnderserved";
  if (trend.sentiment >= 82) return "typeCommunity";
  return "typeSteady";
}

function sourceLabel(source) {
  return {
    social: t("sourceSocial"),
    search: t("sourceSearch"),
    commerce: t("sourceCommerce"),
    news: t("sourceNews")
  }[source] || source;
}

function sourceBreakdown(trend) {
  const base = {
    social: 18 + Math.round(trend.sentiment / 5),
    search: 24 + Math.round(trend.velocity / 3),
    commerce: 18 + Math.round(trend.score / 6),
    news: 12 + Math.round((100 - trend.competition.length * 8) / 7)
  };
  const rows = trend.sources.map((source) => [source, base[source] || 15]);
  const total = rows.reduce((sum, [, value]) => sum + value, 0) || 1;
  return rows.map(([source, value]) => ({
    source,
    label: sourceLabel(source),
    value: Math.max(8, Math.round((value / total) * 100))
  }));
}

function evolutionPoints(trend) {
  return Array.from({ length: 12 }, (_, index) => {
    const progress = index / 11;
    const wave = Math.sin(index * 0.92 + trend.id.length) * 3.4;
    const start = trend.score - trend.velocity * 0.62;
    return clamp(Math.round(start + trend.velocity * progress + wave), 35, 98);
  });
}

function renderEvolutionChart(trend) {
  const values = evolutionPoints(trend);
  const width = 300;
  const height = 118;
  const max = Math.max(...values);
  const min = Math.min(...values);
  const range = Math.max(max - min, 1);
  const points = values.map((value, index) => {
    const x = Math.round((index / (values.length - 1)) * width);
    const y = Math.round(height - ((value - min) / range) * (height - 24) - 12);
    return [x, y];
  });
  const path = points.map(([x, y], index) => `${index === 0 ? "M" : "L"} ${x} ${y}`).join(" ");
  const areaPath = `${path} L ${width} ${height} L 0 ${height} Z`;
  const last = points.at(-1);

  return `
    <svg class="momentum-chart" viewBox="0 0 ${width} ${height}" role="img" aria-label="${t("evolutionLabel")}">
      <path class="momentum-area" d="${areaPath}"></path>
      <path class="momentum-line" d="${path}"></path>
      <circle class="momentum-dot" cx="${last[0]}" cy="${last[1]}" r="4"></circle>
    </svg>
  `;
}

function businessIdeas(trend) {
  return [
    t("businessIdeaProduct", { market: localized(trend.market) }),
    t("businessIdeaService", { name: localized(trend.name) }),
    t("businessIdeaContent", { market: localized(trend.market) })
  ];
}

function selectedTrend(filtered) {
  return (
    filtered.find((trend) => trend.id === state.selectedTrendId) ||
    [...filtered].sort((a, b) => rankingScore(b) - rankingScore(a))[0]
  );
}

function formatLiveTime(date) {
  return new Intl.DateTimeFormat(translations[state.language].htmlLang, {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit"
  }).format(date);
}

function updateLiveSignals() {
  trends.forEach((trend, index) => {
    const marketBias = trend.priority === "high" ? 0.65 : trend.priority === "medium" ? 0.25 : -0.15;
    const wave = Math.sin(Date.now() / 4200 + index * 1.7) * 1.15;
    const noise = (Math.random() - 0.5) * 1.8;
    const scoreDelta = wave + noise + marketBias;
    const velocityDelta = wave * 1.35 + noise * 1.4 + marketBias;

    trend.previousScore = trend.score;
    trend.score = clamp(Math.round(trend.score + scoreDelta), 52, 98);
    trend.velocity = clamp(Math.round(trend.velocity + velocityDelta), 8, 52);
    trend.priority = trend.score >= 84 ? "high" : trend.score >= 70 ? "medium" : "low";
  });
  state.lastUpdated = new Date();
  render();
}

function localizeStaticContent() {
  const languagePack = translations[state.language] || translations.en;
  document.documentElement.lang = languagePack.htmlLang;
  document.documentElement.dir = languagePack.dir;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });

  document.querySelectorAll("[data-category-option]").forEach((node) => {
    node.textContent = categoryLabel(node.dataset.categoryOption);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    node.dataset.i18nAttr.split(",").forEach((pair) => {
      const [attribute, key] = pair.split(":");
      node.setAttribute(attribute, t(key));
    });
  });

  elements.language.value = state.language;
}

function getFilteredTrends() {
  const query = state.query.trim().toLowerCase();

  return trends.filter((trend) => {
    const name = localized(trend.name).toLowerCase();
    const summary = localized(trend.summary).toLowerCase();
    const signals = localized(trend.signals).map((signal) => signal.toLowerCase());
    const matchesQuery =
      !query ||
      name.includes(query) ||
      trend.category.toLowerCase().includes(query) ||
      categoryLabel(trend.category).toLowerCase().includes(query) ||
      summary.includes(query) ||
      signals.some((signal) => signal.includes(query));

    const matchesCategory = state.category === "all" || trend.category === state.category;
    const matchesPriority = state.priority === "all" || trend.priority === state.priority;
    const matchesSources = trend.sources.some((source) => state.sources.has(source));

    return matchesQuery && matchesCategory && matchesPriority && matchesSources;
  });
}

function renderTrend(trend) {
  const isWatched = state.watchlist.has(trend.id);
  const velocity = Math.round(trend.velocity * (state.window / 7));
  const movement = trend.previousScore === undefined ? "stable" : trend.score >= trend.previousScore ? "up" : "down";
  const rank = getFilteredTrends()
    .sort((a, b) => rankingScore(b) - rankingScore(a))
    .findIndex((item) => item.id === trend.id) + 1;
  const card = document.createElement("article");
  card.className = `trend-card ${state.selectedTrendId === trend.id ? "selected" : ""}`;
  card.dataset.trend = trend.id;
  card.innerHTML = `
    <div class="trend-topline">
      <div>
        <h3>${localized(trend.name)}</h3>
        <div class="trend-meta">
          <span class="pill">${categoryLabel(trend.category)}</span>
          <span class="pill market">${t("marketPrefix")}: ${localized(trend.market)}</span>
          <span class="pill type">${t(trendTypeKey(trend))}</span>
          <span class="pill rank">${t("rankLabel", { rank })}</span>
          <span class="pill ${trend.priority}">${t("priorityPrefix")} ${t(priorityTranslationKey(trend.priority))}</span>
          <span class="pill">${t(`competition.${trend.competition}`)} ${t("competitionSuffix")}</span>
        </div>
      </div>
      <div class="score-block ${movement}">
        <strong>${trend.score}</strong>
        <span>${t("scoreLabel")}</span>
      </div>
    </div>
    <p>${localized(trend.summary)}</p>
    <div class="bar-track" aria-label="${t("opportunityScoreAria", { score: trend.score })}">
      <div class="bar-fill" style="width: ${trend.score}%"></div>
    </div>
    <div class="signal-row">
      ${localized(trend.signals).map((signal) => `<span class="pill">${signal}</span>`).join("")}
    </div>
    <div class="trend-actions">
      <span class="velocity">${t("velocityText", { velocity, window: state.window })}</span>
      <button type="button" class="${isWatched ? "active" : ""}" data-watch="${trend.id}">
        ${isWatched ? t("watched") : t("add")}
      </button>
    </div>
  `;
  return card;
}

function renderMetrics(filtered) {
  const average = filtered.length
    ? Math.round(filtered.reduce((sum, trend) => sum + trend.score, 0) / filtered.length)
    : 0;
  const topVelocity = filtered.length
    ? Math.max(...filtered.map((trend) => Math.round(trend.velocity * (state.window / 7))))
    : 0;

  elements.activeCount.textContent = filtered.length;
  elements.averageScore.textContent = average;
  elements.topVelocity.textContent = `${topVelocity}%`;
  elements.watchCount.textContent = state.watchlist.size;
  elements.resultCount.textContent = `${t(filtered.length === 1 ? "results" : "resultsPlural", {
    count: filtered.length
  })} · ${t("liveStatus", { time: formatLiveTime(state.lastUpdated) })}`;
}

function renderChart(filtered) {
  const groups = [
    [t("chartStrong"), filtered.filter((trend) => trend.score >= 85).length],
    [t("chartPromising"), filtered.filter((trend) => trend.score >= 70 && trend.score < 85).length],
    [t("chartWatch"), filtered.filter((trend) => trend.score < 70).length]
  ];
  const max = Math.max(...groups.map(([, count]) => count), 1);

  elements.chart.innerHTML = groups
    .map(
      ([label, count]) => `
        <div class="chart-row">
          <span>${label}</span>
          <div class="chart-bar"><span style="width: ${(count / max) * 100}%"></span></div>
          <strong>${count}</strong>
        </div>
      `
    )
    .join("");
}

function renderInsight(filtered) {
  if (!filtered.length) {
    elements.insight.innerHTML = `<p>${t("noInsight")}</p>`;
    return;
  }

  const leader = [...filtered].sort((a, b) => rankingScore(b) - rankingScore(a))[0];
  const fastest = [...filtered].sort((a, b) => b.velocity - a.velocity)[0];
  const selected = selectedTrend(filtered);
  const breakdown = sourceBreakdown(selected);
  const topSource = breakdown[0];
  const selectedVelocity = Math.round(selected.velocity * (state.window / 7));

  elements.insight.innerHTML = `
    <p>${t("leaderInsight", { name: `<strong>${localized(leader.name)}</strong>` })}</p>
    <p>${t("fastestInsight", {
      name: `<strong>${localized(fastest.name)}</strong>`,
      velocity: Math.round(fastest.velocity * (state.window / 7)),
      window: state.window
    })}</p>
    <div class="trend-detail">
      <div class="detail-heading">
        <span>${t("clickForDetails")}</span>
        <strong>${localized(selected.name)}</strong>
      </div>
      <div class="detail-pills">
        <span class="pill type">${t("trendTypeLabel")}: ${t(trendTypeKey(selected))}</span>
        <span class="pill market">${t("marketPrefix")}: ${localized(selected.market)}</span>
      </div>
      <section>
        <h3>${t("evolutionLabel")}</h3>
        ${renderEvolutionChart(selected)}
      </section>
      <section>
        <h3>${t("sourceBreakdownLabel")}</h3>
        <div class="source-breakdown">
          ${breakdown
            .map(
              (row) => `
                <div class="source-row">
                  <span>${row.label}</span>
                  <div class="source-track"><span style="width: ${row.value}%"></span></div>
                  <strong>${row.value}%</strong>
                </div>
              `
            )
            .join("")}
        </div>
      </section>
      <section>
        <h3>${t("whyNowLabel")}</h3>
        <p>${t("whyNowTemplate", {
          market: `<strong>${localized(selected.market)}</strong>`,
          source: `<strong>${topSource.label}</strong>`,
          velocity: selectedVelocity,
          competition: t(`competition.${selected.competition}`).toLowerCase()
        })}</p>
      </section>
      <section>
        <h3>${t("businessIdeasLabel")}</h3>
        <ul class="idea-list">
          ${businessIdeas(selected).map((idea) => `<li>${idea}</li>`).join("")}
        </ul>
      </section>
    </div>
  `;
}

function render() {
  localizeStaticContent();
  const filtered = getFilteredTrends();
  elements.list.innerHTML = "";

  if (!filtered.length) {
    const empty = document.createElement("div");
    empty.className = "empty-state";
    empty.textContent = t("empty");
    elements.list.append(empty);
  } else {
    if (!filtered.some((trend) => trend.id === state.selectedTrendId)) {
      state.selectedTrendId = [...filtered].sort((a, b) => rankingScore(b) - rankingScore(a))[0].id;
    }
    filtered
      .sort((a, b) => rankingScore(b) - rankingScore(a))
      .forEach((trend) => elements.list.append(renderTrend(trend)));
  }

  renderMetrics(filtered);
  renderChart(filtered);
  renderInsight(filtered);
}

